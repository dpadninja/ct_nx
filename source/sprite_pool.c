static void  (*Node_setRotation)(void *, float);
static const BlendFunc *s_blend_premul; // BlendFunc::ALPHA_PREMULTIPLIED

static const Vec2 k_anchor_mid = { 0.5f, 0.5f };
static const Color3B k_white = { 255, 255, 255 };

// Put a pooled sprite's site-changed properties back to fresh values.
static void reset_sprite(void *s, uint32_t m, void *fresh_state) {
  if (m & R_POS)     { Sprite_setPosition(s, 0.f, 0.f); Sprite_setPositionZ(s, 0.f); }
  if (m & R_SCALE)   Sprite_setScale(s, 1.f);
  if (m & R_ROT)     { Sprite_setRotation(s, 0.f); Sprite_setRotationSkewX(s, 0.f); Sprite_setRotationSkewY(s, 0.f); }
  if (m & R_SKEW)    { Sprite_setSkewX(s, 0.f); Sprite_setSkewY(s, 0.f); }
  if (m & R_ANCHOR)  Sprite_setAnchorPoint(s, &k_anchor_mid);
  if (m & R_VIS)     Sprite_setVisible(s, 1);
  if (m & R_FLIP)    { Sprite_setFlippedX(s, 0); Sprite_setFlippedY(s, 0); }
  if (m & R_OPAC)    Node_setOpacity(s, 255);
  if (m & R_COLOR)   Node_setColor(s, &k_white);
  if (m & R_SHADER)  Node_setGLProgramState(s, fresh_state);
  if (m & R_GZ)      Node_setGlobalZOrder(s, 0.f);
  if (m & R_IGNANCH) Sprite_setIgnoreAnchor(s, 0);
}

// Same for a render texture and its inner sprite (fresh: flipped Y,
// premultiplied blend, opacity-modify-RGB on; see RenderTexture::init...).
static void reset_rt(void *rt, uint32_t m) {
  if (m & R_POS)   Node_setPosition(rt, 0.f, 0.f);
  if (m & R_SCALE) Node_setScale(rt, 1.f);
  if (m & R_ROT)   Node_setRotation(rt, 0.f);
  void *s = *(void **)((uintptr_t)rt + RT_SPRITE_FIELD);
  if (!s) return;
  if (m & R_C_POS)    { Sprite_setPosition(s, 0.f, 0.f); Sprite_setPositionZ(s, 0.f); }
  if (m & R_C_SCALE)  Sprite_setScale(s, 1.f);
  if (m & R_C_ANCHOR) Sprite_setAnchorPoint(s, &k_anchor_mid);
  if (m & R_C_FLIP)   { Sprite_setFlippedX(s, 0); Sprite_setFlippedY(s, 1); }
  if (m & R_C_OPAC)   Node_setOpacity(s, 255);
  if (m & R_C_COLOR)  Node_setColor(s, &k_white);
  if (m & R_C_BLEND)  { Sprite_setBlendFunc(s, s_blend_premul); Sprite_setOpacityModifyRGB(s, 1); }
}

static void release_site(Site *s) {
  for (int i = 0; i < s->size; i++) {
    if (s->state && s->state[i]) Ref_release(s->state[i]);
    if (s->obj[i]) Ref_release(s->obj[i]);
  }
  free(s->obj); free(s->state); free(s->w); free(s->h);
  s->obj = NULL; s->state = NULL; s->w = s->h = NULL;
  s->size = s->idx = 0;
}

// Make room for slot s->idx; 0 if the pool is full or out of memory.
static int reserve(Site *s) {
  if (s->idx >= POOL_MAX) return 0;
  if (s->idx < s->size) return 1;
  int n = s->size ? s->size * 2 : 16;
  if (n > POOL_MAX) n = POOL_MAX;
  void **o = realloc(s->obj, n * sizeof(void *));
  if (!o) return 0;
  s->obj = o;
  void **st = realloc(s->state, n * sizeof(void *));
  if (!st) return 0;
  s->state = st;
  int *w = realloc(s->w, n * sizeof(int));
  if (!w) return 0;
  s->w = w;
  int *h = realloc(s->h, n * sizeof(int));
  if (!h) return 0;
  s->h = h;
  for (int i = s->size; i < n; i++) { o[i] = NULL; st[i] = NULL; w[i] = h[i] = 0; }
  s->size = n;
  return 1;
}

static Site *s_on[NUM_SITES]; // active sites, ascending return address
static int s_num_on;

static Site *find_site(uintptr_t ret, int kind) {
  int lo = 0, hi = s_num_on - 1;
  while (lo <= hi) {
    const int mid = (lo + hi) / 2;
    Site *s = s_on[mid];
    if (s->ret == ret) return s->def->kind == kind ? s : NULL;
    if (s->ret < ret) lo = mid + 1; else hi = mid - 1;
  }
  return NULL;
}

static void *sprite_hook(void *tex, const void *rect, int rotated) {
  if (rotated & 0xff) // C++ bool arg: only the low byte is defined
    return s_sprite_next(tex, rect, rotated);
  Site *s = find_site((uintptr_t)__builtin_return_address(0), K_SPRITE);
  if (!s || !reserve(s))
    return s_sprite_next(tex, rect, rotated);
  s->last_used = s_frame;
  void *spr = s->obj[s->idx];
  if (!spr) {
    spr = s_sprite_real(tex, rect, 0);
    if (!spr) return NULL;
    Ref_retain(spr); // outlive the end-of-frame autorelease drain
    s->obj[s->idx] = spr;
    if (s->def->mask & R_SHADER) {
      void *st = Node_getGLProgramState(spr);
      if (st) Ref_retain(st);
      s->state[s->idx] = st;
    }
  } else {
    if (Sprite_getTexture(spr) != tex)
      Sprite_setTexture(spr, tex);
    Sprite_setTextureRect(spr, rect);
    Sprite_updateBlendFunc(spr); // default blend + opacity-modify-RGB for the texture
    reset_sprite(spr, s->def->mask, s->state[s->idx]);
  }
  s->idx++;
  return spr;
}

static void *rt_hook(int w, int h) {
  Site *s = find_site((uintptr_t)__builtin_return_address(0), K_RT);
  if (!s || !reserve(s))
    return s_rt_next(w, h);
  s->last_used = s_frame;
  void *rt = s->obj[s->idx];
  if (rt && (s->w[s->idx] != w || s->h[s->idx] != h)) {
    Ref_release(rt); // last used in an earlier frame; size changed
    rt = s->obj[s->idx] = NULL;
  }
  if (!rt) {
    rt = s_rt_real(w, h);
    if (!rt) return NULL;
    Ref_retain(rt);
    s->obj[s->idx] = rt;
    s->w[s->idx] = w;
    s->h[s->idx] = h;
  } else {
    reset_rt(rt, s->def->mask);
  }
  s->idx++;
  return rt;
}

void sprite_pool_frame(void) {
  if (!s_active) return;
  s_frame++;
  for (int i = 0; i < NUM_SITES; i++) {
    Site *s = &s_site[i];
    s->idx = 0;
    if (s->size && s_frame - s->last_used > TRIM_AFTER)
      release_site(s);
  }
}

// Point every JUMP_SLOT relocation for `name` at `dst`; returns the previous
// value of the first matching slot (0 if none). Must run before so_finalize.
static uintptr_t hook_got(so_module *mod, const char *name, uintptr_t dst) {
  uintptr_t prev = 0;
  for (int i = 0; i < mod->elf_hdr->e_shnum; i++) {
    const char *sh_name = mod->shstrtab + mod->sec_hdr[i].sh_name;
    if (strcmp(sh_name, ".rela.plt") != 0) continue;
    Elf64_Rela *rels = (Elf64_Rela *)((uintptr_t)mod->load_base + mod->sec_hdr[i].sh_addr);
    const size_t cnt = mod->sec_hdr[i].sh_size / sizeof(Elf64_Rela);
    for (size_t j = 0; j < cnt; j++) {
      if (ELF64_R_TYPE(rels[j].r_info) != R_AARCH64_JUMP_SLOT) continue;
      const Elf64_Sym *sym = &mod->syms[ELF64_R_SYM(rels[j].r_info)];
      if (strcmp(mod->dynstrtab + sym->st_name, name) != 0) continue;
      uintptr_t *slot = (uintptr_t *)((uintptr_t)mod->load_base + rels[j].r_offset);
      if (!prev) prev = *slot;
      *slot = dst;
    }
  }
  return prev;
}

#define RESOLVE(var, sym) \
  do { *(uintptr_t *)&(var) = so_try_find_addr_rx(mod, sym); \
       if (!(var)) { debugPrintf("reuse_draw_objects: missing %s, not applied\n", sym); return; } } while (0)

void apply_sprite_pool(so_module *mod) {
  if (!config.reuse_draw_objects) return;

  static const char *SYM_SPRITE = "_ZN7cocos2d6Sprite17createWithTextureEPNS_9Texture2DERKNS_4RectEb";
  static const char *SYM_RT     = "_ZN7cocos2d13RenderTexture6createEii";
  RESOLVE(s_sprite_real, SYM_SPRITE);
  RESOLVE(s_rt_real, SYM_RT);
  RESOLVE(Ref_retain, "_ZN7cocos2d3Ref6retainEv");
  RESOLVE(Ref_release, "_ZN7cocos2d3Ref7releaseEv");
  RESOLVE(Sprite_getTexture, "_ZNK7cocos2d6Sprite10getTextureEv");
  RESOLVE(Sprite_setTexture, "_ZN7cocos2d6Sprite10setTextureEPNS_9Texture2DE");
  RESOLVE(Sprite_setTextureRect, "_ZN7cocos2d6Sprite14setTextureRectERKNS_4RectE");
  RESOLVE(Sprite_updateBlendFunc, "_ZN7cocos2d6Sprite15updateBlendFuncEv");
  RESOLVE(Sprite_setPosition, "_ZN7cocos2d6Sprite11setPositionEff");
  RESOLVE(Sprite_setPositionZ, "_ZN7cocos2d6Sprite12setPositionZEf");
  RESOLVE(Sprite_setScale, "_ZN7cocos2d6Sprite8setScaleEf");
  RESOLVE(Sprite_setRotation, "_ZN7cocos2d6Sprite11setRotationEf");
  RESOLVE(Sprite_setRotationSkewX, "_ZN7cocos2d6Sprite16setRotationSkewXEf");
  RESOLVE(Sprite_setRotationSkewY, "_ZN7cocos2d6Sprite16setRotationSkewYEf");
  RESOLVE(Sprite_setSkewX, "_ZN7cocos2d6Sprite8setSkewXEf");
  RESOLVE(Sprite_setSkewY, "_ZN7cocos2d6Sprite8setSkewYEf");
  RESOLVE(Sprite_setAnchorPoint, "_ZN7cocos2d6Sprite14setAnchorPointERKNS_4Vec2E");
  RESOLVE(Sprite_setVisible, "_ZN7cocos2d6Sprite10setVisibleEb");
  RESOLVE(Sprite_setFlippedX, "_ZN7cocos2d6Sprite11setFlippedXEb");
  RESOLVE(Sprite_setFlippedY, "_ZN7cocos2d6Sprite11setFlippedYEb");
  RESOLVE(Sprite_setIgnoreAnchor, "_ZN7cocos2d6Sprite31setIgnoreAnchorPointForPositionEb");
  RESOLVE(Sprite_setBlendFunc, "_ZN7cocos2d6Sprite12setBlendFuncERKNS_9BlendFuncE");
  RESOLVE(Sprite_setOpacityModifyRGB, "_ZN7cocos2d6Sprite19setOpacityModifyRGBEb");
  RESOLVE(Node_setOpacity, "_ZN7cocos2d4Node10setOpacityEh");
  RESOLVE(Node_setColor, "_ZN7cocos2d4Node8setColorERKNS_7Color3BE");
  RESOLVE(Node_setGlobalZOrder, "_ZN7cocos2d4Node15setGlobalZOrderEf");
  RESOLVE(Node_getGLProgramState, "_ZNK7cocos2d4Node17getGLProgramStateEv");
  RESOLVE(Node_setGLProgramState, "_ZN7cocos2d4Node17setGLProgramStateEPNS_14GLProgramStateE");
  RESOLVE(Node_setPosition, "_ZN7cocos2d4Node11setPositionEff");
  RESOLVE(Node_setScale, "_ZN7cocos2d4Node8setScaleEf");
  RESOLVE(Node_setRotation, "_ZN7cocos2d4Node11setRotationEf");
  RESOLVE(s_blend_premul, "_ZN7cocos2d9BlendFunc19ALPHA_PREMULTIPLIEDE");

  // Each site must still be a `bl` to the expected factory stub in this
  // build of the library; anything else is left alone.
  const uintptr_t base = (uintptr_t)mod->load_base;
  const uintptr_t vbase = (uintptr_t)mod->load_virtbase;
  int on = 0;
  for (int i = 0; i < NUM_SITES; i++) {
    const SiteDef *d = &k_sites[i];
    s_site[i].def = d;
    s_site[i].ret = 0;
    if (d->offset + 4 > mod->load_size) continue;
    const uint32_t insn = *(const uint32_t *)(base + d->offset);
    if ((insn & 0xfc000000u) != 0x94000000u) continue; // not a bl
    const int64_t imm = ((int64_t)(int32_t)(insn << 6)) >> 4; // imm26 * 4
    const uintptr_t want = d->kind == K_RT ? PLT_RT_CREATE : PLT_SPRITE_CREATE;
    if ((uintptr_t)(d->offset + imm) != want) continue;
    s_site[i].ret = vbase + d->offset + 4;
    s_on[on++] = &s_site[i]; // k_sites is sorted by offset, so s_on is sorted by ret
  }
  s_num_on = on;
  if (!on) {
    debugPrintf("reuse_draw_objects: no call site matches this libchrono build, not applied\n");
    return;
  }

  s_sprite_next = (void *)hook_got(mod, SYM_SPRITE, (uintptr_t)&sprite_hook);
  s_rt_next = (void *)hook_got(mod, SYM_RT, (uintptr_t)&rt_hook);
  if (!s_sprite_next || !s_rt_next) {
    // put back whichever hook did go in, and give up
    if (s_sprite_next) hook_got(mod, SYM_SPRITE, (uintptr_t)s_sprite_next);
    if (s_rt_next) hook_got(mod, SYM_RT, (uintptr_t)s_rt_next);
    debugPrintf("reuse_draw_objects: factory GOT slot not found, not applied\n");
    return;
  }
  s_active = 1;
  debugPrintf("reuse_draw_objects: %d/%d call sites pooled\n", on, NUM_SITES);
}
