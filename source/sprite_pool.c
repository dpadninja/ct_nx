/* sprite_pool.c -- reuse the engine's throw-away draw objects (config: reuse_draw_objects)
 *
 * WHY
 * The engine draws in "immediate mode": for every element, every frame, it
 * creates a cocos2d object, sets it up, draws it once and lets the autorelease
 * pool destroy it at the end of the frame. Usually that's a few dozen sprites,
 * but some effects create hundreds of sprites (one per scanline or per tile)
 * or even a whole off-screen RenderTexture (texture + framebuffer) per frame,
 * which costs tens of milliseconds of CPU at stock clocks: the wavy cloud
 * layer and the Black Omen on the world map, tiled battle effect backgrounds
 * (e.g. Haste), field raster effects, and so on.
 *
 * WHAT THIS DOES
 * libchrono calls Sprite::createWithTexture(tex, rect, bool) and
 * RenderTexture::create(int, int) through its PLT, so their GOT slots point at
 * the hooks below. A call from one of the sites in pool_sites.h gets an object
 * from that site's pool instead of a new one; any other call passes straight
 * through. Pools rewind at the start of every frame (sprite_pool_frame), so a
 * pooled object is used at most once per frame, after the previous frame's
 * render commands have all executed.
 *
 * pool_sites.h is generated by tools/pool_analyze.py, which proves for each
 * site that the object never outlives the frame (never stored outside the
 * stack frame, passed as an argument, returned, or written into) and is only
 * drawn, read, or changed through known setters. Before an object is handed
 * out again, every property group the site may change is put back to the
 * value a freshly created object has, so the site sees exactly what the
 * factory would have returned:
 *   - sprites: texture + rect (from the call's own arguments), default blend
 *     function / opacity-modify-RGB for the texture, plus the site's groups
 *     (position, scale, rotation, skew, anchor, visibility, flip, opacity,
 *     colour, shader, global Z, ignore-anchor);
 *   - render textures: same size required; the analysis only accepts sites
 *     whose first use of the contents is a full clear (beginWithClear), so
 *     last frame's pixels are never seen; position/scale/rotation and the
 *     inner sprite's groups are reset as above.
 * Sites unused for ~10 s release their objects (and the textures they hold).
 */

