static void *(*s_sprite_real)(void *, const void *, int);
static void *(*s_rt_next)(int, int);
static void *(*s_rt_real)(int, int);

static void  (*Ref_retain)(void *);
static void  (*Ref_release)(void *);
static void *(*Sprite_getTexture)(void *);
