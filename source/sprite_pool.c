static void  (*Sprite_setRotation)(void *, float);
static void  (*Sprite_setRotationSkewX)(void *, float);
static void  (*Sprite_setRotationSkewY)(void *, float);
static void  (*Sprite_setSkewX)(void *, float);
static void  (*Sprite_setSkewY)(void *, float);
